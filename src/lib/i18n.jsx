const LangContext = createContext(null);

export function LangProvider({ children }) {
  const [lang, setLang] = useState(() => {
    try { return localStorage.getItem('rabbit_lang') || 'zh'; } catch { return 'zh'; }
  });

  useEffect(() => {
    try { localStorage.setItem('rabbit_lang', lang); } catch {}
  }, [lang]);

  const t = STRINGS[lang] || STRINGS.zh;
  const toggle = () => setLang((l) => (l === 'zh' ? 'en' : 'zh'));

  return (
    <LangContext.Provider value={{ lang, setLang, t, toggle }}>
      {children}
    </LangContext.Provider>
  );
}

export function useLang() {
  const ctx = useContext(LangContext);
  if (!ctx) {
    console.warn('useLang was called outside LangProvider, returning fallback strings.');
    return {
      lang: 'zh',
      setLang: () => {},
      t: STRINGS.zh,
      toggle: () => {},
    };
  }
  return ctx;
}

export const useI18n = useLang;
export const I18nProvider = LangProvider;
export { STRINGS };
export default LangProvider;
